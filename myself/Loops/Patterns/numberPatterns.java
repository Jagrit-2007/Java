package Loops.Patterns;

public class numberPatterns {
    
    public static void main(String[] args) {
        
        // BASIC NUMBER TRIANGLE

        int num1 = 5;
        for(int i = 1; i <= num1; i++)
        {
            for(int j = 1; j <= i; j++)
            {
                System.out.print(j + " ");
            }
            System.out.println();
        }

        // FLOYD'S TRIANGLE (CONTINOUS NUMBERS)

        // 0-1 TRIANGLE (BINARY)

        // NUMBER PALINDROME PYRAMID

        // ALPHABET/CHARACTER PATTERNS

        // HOLLOW RECTANGLE

        // BUTTERFLY PATTERN
    }
}
